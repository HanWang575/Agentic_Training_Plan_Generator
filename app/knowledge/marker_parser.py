"""Optional Marker PDF parser integration.

Marker is intentionally optional because it is a large dependency. When it is
installed, this module runs `marker_single` and converts Markdown output into
semantic text/table blocks used by the normal upload pipeline.
"""

from collections.abc import Callable
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

from app.core.config import Settings
from app.knowledge.schemas import ParsedTextBlock
from app.knowledge.text_quality import clean_pdf_text


def parse_pdf_with_marker(
    file_path: Path,
    settings: Settings,
    progress_callback: Callable[[float, str], None] | None = None,
) -> tuple[list[ParsedTextBlock], list[str]]:
    """Parse a PDF with Marker and return semantic Markdown-derived blocks.

    Parameters:
        file_path: PDF path.
        settings: runtime settings controlling GPU device, OCR, and timeout.
        progress_callback: optional `(progress, message)` callback.
    Returns:
        tuple: parsed blocks and parser warnings.
    Raises:
        RuntimeError: when Marker is not installed or conversion fails.
    """

    marker_single = _marker_single_from_venv()
    if marker_single is None:
        marker_single = shutil.which("marker_single")
    if marker_single is None:
        raise RuntimeError("Marker is not installed; `marker_single` was not found.")

    pdf_path = file_path.resolve()
    with tempfile.TemporaryDirectory(prefix="marker_pdf_") as tmp_dir:
        env = os.environ.copy()
        if settings.marker_torch_device:
            env["TORCH_DEVICE"] = settings.marker_torch_device.strip()
        markdown = _run_marker_in_batches(
            pdf_path=pdf_path,
            marker_single=marker_single,
            output_root=Path(tmp_dir),
            settings=settings,
            env=env,
            progress_callback=progress_callback,
        )
        blocks = markdown_to_blocks(markdown)
        warnings = [
            f"parsed with Marker using TORCH_DEVICE={env.get('TORCH_DEVICE', 'unset')}; "
            f"force_ocr={settings.marker_force_ocr}"
        ]
        return blocks, warnings


def markdown_to_blocks(markdown: str) -> list[ParsedTextBlock]:
    """Convert Marker Markdown into semantic plain-text and table blocks.

    Parameters:
        markdown: Markdown generated by Marker.
    Returns:
        list[ParsedTextBlock]: blocks with `content_type` set to `plain_text`
        or `table`.
    """

    blocks: list[ParsedTextBlock] = []
    current_heading: str | None = None
    paragraph_lines: list[str] = []
    recent_paragraph: str | None = None
    lines = markdown.splitlines()
    index = 0

    def flush_paragraph() -> None:
        nonlocal paragraph_lines, recent_paragraph
        if not paragraph_lines:
            return
        text = clean_pdf_text("\n".join(paragraph_lines))
        paragraph_lines = []
        if not text:
            return
        blocks.append(
            ParsedTextBlock(
                text=text,
                section_heading=current_heading,
                content_type="plain_text",
            )
        )
        recent_paragraph = text

    while index < len(lines):
        line = lines[index].rstrip()
        heading = _parse_heading(line)
        if heading:
            flush_paragraph()
            current_heading = heading["text"]
            blocks.append(
                ParsedTextBlock(
                    text=heading["text"],
                    section_heading=heading["text"],
                    content_type="plain_text",
                    content_metadata={"role": "heading", "heading_level": heading["level"]},
                )
            )
            recent_paragraph = None
            index += 1
            continue

        image = _parse_markdown_image(line)
        if image:
            flush_paragraph()
            blocks.append(
                _figure_block(
                    alt_text=image["alt_text"],
                    image_path=image["image_path"],
                    section_heading=current_heading,
                )
            )
            recent_paragraph = None
            index += 1
            continue

        if _is_markdown_table_start(lines, index):
            flush_paragraph()
            table_lines = [lines[index].rstrip(), lines[index + 1].rstrip()]
            index += 2
            while index < len(lines) and "|" in lines[index]:
                table_lines.append(lines[index].rstrip())
                index += 1
            footnote_lines = []
            while index < len(lines) and _is_table_note_line(lines[index]):
                footnote_lines.append(lines[index].strip())
                index += 1
            table_block = _table_block(
                table_lines=table_lines,
                section_heading=current_heading,
                footnote="\n".join(footnote_lines).strip() or None,
            )
            blocks.append(table_block)
            recent_paragraph = None
            continue

        if _is_html_table_start(line):
            flush_paragraph()
            table_lines = [line]
            index += 1
            while index < len(lines):
                table_lines.append(lines[index].rstrip())
                if "</table>" in lines[index].lower():
                    index += 1
                    break
                index += 1
            blocks.append(
                _table_block(
                    table_lines=[_html_table_to_markdown("\n".join(table_lines))],
                    section_heading=current_heading,
                    footnote=None,
                )
            )
            recent_paragraph = None
            continue

        if line.strip():
            paragraph_lines.append(line)
        else:
            flush_paragraph()
        index += 1

    flush_paragraph()
    return blocks


def _marker_single_from_venv() -> str | None:
    """Return the console script path inside the active Python environment."""

    scripts_dir = Path(sys.executable).resolve().parent
    for name in ("marker_single.exe", "marker_single"):
        candidate = scripts_dir / name
        if candidate.exists():
            return str(candidate)
    return None


def _find_marker_markdown(output_dir: Path) -> Path | None:
    """Find the Markdown file emitted by Marker."""

    markdown_files = sorted(output_dir.rglob("*.md"))
    return markdown_files[0] if markdown_files else None


def _run_marker_in_batches(
    pdf_path: Path,
    marker_single: str,
    output_root: Path,
    settings: Settings,
    env: dict[str, str],
    progress_callback: Callable[[float, str], None] | None,
) -> str:
    """Run Marker in page batches so the caller can surface progress."""

    page_ranges = _marker_page_ranges(pdf_path, settings.marker_page_batch_size)
    markdown_parts: list[str] = []
    total_batches = max(len(page_ranges), 1)
    for batch_index, page_range in enumerate(page_ranges, start=1):
        display_range = _display_page_range(page_range)
        if progress_callback is not None:
            progress_callback(
                max(0.02, (batch_index - 1) / total_batches * 0.9),
                f"Marker parsing pages {display_range} ({batch_index} of {total_batches})",
            )
        output_dir = output_root / f"batch_{batch_index:04d}"
        command = [
            marker_single,
            str(pdf_path),
            "--output_format",
            "markdown",
            "--output_dir",
            str(output_dir),
            "--page_range",
            page_range,
        ]
        if settings.marker_force_ocr:
            command.append("--force_ocr")
        result = subprocess.run(
            command,
            cwd=str(pdf_path.parent),
            env=env,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=settings.marker_timeout_seconds,
        )
        if result.returncode != 0:
            raise RuntimeError(
                "Marker failed: "
                + (result.stderr.strip() or result.stdout.strip() or f"exit code {result.returncode}")
            )
        markdown_path = _find_marker_markdown(output_dir)
        if markdown_path is None:
            raise RuntimeError("Marker completed but no Markdown output was found.")
        markdown_parts.append(markdown_path.read_text(encoding="utf-8", errors="replace"))
        if progress_callback is not None:
            progress_callback(
                min(0.9, batch_index / total_batches * 0.9),
                f"Marker finished pages {display_range} ({batch_index} of {total_batches})",
            )
    return "\n\n".join(markdown_parts)


def _marker_page_ranges(pdf_path: Path, batch_size: int) -> list[str]:
    """Split one PDF into zero-based Marker `page_range` strings."""

    import fitz

    with fitz.open(pdf_path) as document:
        total_pages = len(document)
    if total_pages <= 0:
        return ["0"]
    safe_batch_size = max(1, batch_size)
    ranges = []
    for start_index in range(0, total_pages, safe_batch_size):
        start_page = start_index
        end_page = min(total_pages - 1, start_index + safe_batch_size - 1)
        ranges.append(
            str(start_page) if start_page == end_page else f"{start_page}-{end_page}"
        )
    return ranges


def _display_page_range(page_range: str) -> str:
    """Convert one zero-based Marker page range into a user-friendly label."""

    if "-" not in page_range:
        return str(int(page_range) + 1)
    start_text, end_text = page_range.split("-", maxsplit=1)
    return f"{int(start_text) + 1}-{int(end_text) + 1}"


def _parse_heading(line: str) -> dict[str, int | str] | None:
    """Return Markdown heading text and level if the line is a heading."""

    match = re.match(r"^\s{0,3}(#{1,6})\s+(.+?)\s*$", line)
    if not match:
        return None
    return {"text": match.group(2).strip(), "level": len(match.group(1))}


def _parse_markdown_image(line: str) -> dict[str, str] | None:
    """Parse a Markdown image line into figure metadata."""

    match = re.match(r"^\s*!\[(?P<alt>[^\]]*)\]\((?P<path>[^)]+)\)\s*$", line)
    if not match:
        return None
    return {
        "alt_text": match.group("alt").strip(),
        "image_path": match.group("path").strip(),
    }


def _is_markdown_table_start(lines: list[str], index: int) -> bool:
    """Detect a GitHub-style Markdown table."""

    if index + 1 >= len(lines):
        return False
    header = lines[index]
    separator = lines[index + 1]
    return "|" in header and re.match(r"^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*$", separator) is not None


def _is_html_table_start(line: str) -> bool:
    """Detect an HTML table emitted inside Markdown."""

    return "<table" in line.lower()


def _html_table_to_markdown(html: str) -> str:
    """Convert a simple HTML table into Markdown rows."""

    from bs4 import BeautifulSoup

    soup = BeautifulSoup(html, "html.parser")
    rows = []
    for row in soup.find_all("tr"):
        cells = [cell.get_text(" ", strip=True) for cell in row.find_all(["th", "td"])]
        if cells:
            rows.append(cells)
    if not rows:
        return html.strip()
    width = max(len(row) for row in rows)
    normalized_rows = [row + [""] * (width - len(row)) for row in rows]
    header = normalized_rows[0]
    separator = ["---"] * width
    body = normalized_rows[1:]
    markdown_rows = [header, separator, *body]
    return "\n".join("| " + " | ".join(row) + " |" for row in markdown_rows)


def _is_table_note_line(line: str) -> bool:
    """Detect short note/footnote lines immediately following a table."""

    stripped = line.strip()
    if not stripped:
        return False
    return bool(
        re.match(r"^(note|notes|footnote|source)(?::|\uFF1A)", stripped, flags=re.IGNORECASE)
    )


