def _table_block(
    table_lines: list[str],
    section_heading: str | None,
    footnote: str | None,
) -> ParsedTextBlock:
    """Build one parsed table block without guessed title/description metadata."""

    metadata: dict[str, Any] = {
        "table_footnote": footnote,
        "table_format": "markdown",
    }
    metadata = {key: value for key, value in metadata.items() if value}
    pieces = ["Content type: table"]
    pieces.append("\n".join(table_lines).strip())
    if footnote:
        pieces.append(f"Table footnote: {footnote}")
    return ParsedTextBlock(
        text="\n\n".join(pieces).strip(),
        section_heading=section_heading,
        content_type="table",
        content_metadata=metadata,
    )


def _figure_block(
    alt_text: str,
    image_path: str,
    section_heading: str | None,
) -> ParsedTextBlock:
    """Build one parsed figure block with nearby descriptive context."""

    metadata: dict[str, Any] = {
        "image_alt_text": alt_text,
        "image_path": image_path,
    }
    metadata = {key: value for key, value in metadata.items() if value}
    pieces = ["Content type: figure"]
    if alt_text:
        pieces.append(f"Figure alt text: {alt_text}")
    pieces.append(f"Image path: {image_path}")
    return ParsedTextBlock(
        text="\n\n".join(pieces).strip(),
        section_heading=section_heading,
        content_type="figure",
        content_metadata=metadata,
    )


def _split_markdown_row(row: str) -> list[str]:
    """Split one Markdown table row into cleaned cell values."""

    cells = [cell.strip() for cell in row.strip().strip("|").split("|")]
    return [cell for cell in cells if cell]


